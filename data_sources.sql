-- 1. Cap1 deals (the base list; every other table joins onto this)
SELECT OPPORTUNITY_ID, SALESFORCE_ACCOUNT_ID, REGION, DISTRICT,
       ORIGINAL_OPPORTUNITY_REGION, ORIGINAL_OPPORTUNITY_DISTRICT,
       FISCAL_YEAR, FQ_NUM, FISCAL_QUARTER, CLOSE_DATE, RVP, OWNER,
       CAP1_ACV, PARTNER_ASSISTS
FROM SALES.RAVEN.SDA_CLOSED_OPPORTUNITY_BOOKINGS_VIEW
WHERE IS_CAP1 = TRUE
  AND FISCAL_YEAR = 2027
  AND OPPORTUNITY_ID NOT IN ('006VI00000zvrqrYAA','006VI00000xValGYAS'); -- Resolve AI (misclassified)

-- 2. ACE coverage: TMR
SELECT ACCOUNT_ID, REQUEST_CREATED_DATE
FROM SALES.SALES_ENGINEERING.FIELD_SPECIALIST_REQUESTS_DX_ELEMENTUM
WHERE SPECIALIST_TYPE IN ('Account Engineer','Activation SE - AMS Acq ONLY')
  AND ACCOUNT_ID IS NOT NULL;

-- 3. ACE coverage: #activation tag on a use case
SELECT SALESFORCE_ACCOUNT_ID, SALESFORCE_USE_CASE_CREATED_DATE
FROM SALES.SE_REPORTING.DD_SOLUTION_ENGINEER_SALESFORCE_USE_CASE
WHERE SALESFORCE_USE_CASE_IMPLEMENTATION_COMMENTS ILIKE '%#activation%'
  AND SALESFORCE_ACCOUNT_ID IS NOT NULL;

-- 4. ACE coverage: ACE on the use case team
SELECT SALESFORCE_ACCOUNT_ID, SALESFORCE_USE_CASE_TEAM_CREATED_AT
FROM SALES.SE_REPORTING.DD_SALESFORCE_USE_CASE_TEAM
WHERE SALESFORCE_USE_CASE_TEAM_ROLE IN ('SE - Account Engineer','SE - Activation')
  AND IS_SALESFORCE_USE_CASE_TEAM_SALESFORCE_DELETED = FALSE
  AND SALESFORCE_ACCOUNT_ID IS NOT NULL;

-- 5. ACE coverage: ACE on the account team
SELECT ACCOUNT_ID, CREATED_DATE
FROM FIVETRAN.SALESFORCE.ACCOUNT_TEAM_MEMBER
WHERE TEAM_MEMBER_ROLE IN ('SE - Account Engineer','SE - Activation')
  AND IS_DELETED = FALSE
  AND _FIVETRAN_DELETED = FALSE
  AND ACCOUNT_ID IS NOT NULL;

-- 6. Use cases: SI partner, any partner, PS engagement
SELECT SALESFORCE_ACCOUNT_ID, SALESFORCE_PARTNER_NAME, IS_PARTNER_ATTACHED,
       IS_DEPLOYED, IS_LOST, SALESFORCE_USE_CASE_STAGE, PS_ENGAGEMENT
FROM SALES.SE_REPORTING.DD_SOLUTION_ENGINEER_SALESFORCE_USE_CASE
WHERE SALESFORCE_ACCOUNT_ID IS NOT NULL;

-- 7. Deal registrations (SI partner on the deal)
SELECT OPPORTUNITY_ID, PARTNER_NAME
FROM SALES.RAVEN.SDA_DEAL_REGISTRATION_VIEW
WHERE DEAL_REG_STATUS IN ('Approved Deal Registration Opportunity',
                          'Closed Won Deal Registration Opportunity')
  AND OPPORTUNITY_ID IS NOT NULL;

-- 8. OD flip + topic signals (Salesforce opportunities)
SELECT ID, ACCOUNT_ID, STAGE_NAME, AGREEMENT_TYPE_C, IS_DELETED,
       USE_CASES_C, ETL_TOOL_C, CURRENT_DW_TOOL_C, CURRENT_BI_TOOL_C
FROM FIVETRAN.SALESFORCE.OPPORTUNITY
WHERE IS_DELETED = FALSE;

-- 9. Consumption (12-month total, lifetime, last 30 days)
SELECT SALESFORCE_ACCOUNT_ID, GENERAL_DATE, REVENUE
FROM SALES.RAVEN.A360_REVENUE_CONSUMPTION_VIEW
WHERE SALESFORCE_ACCOUNT_ID IS NOT NULL;

-- 10. Account details
SELECT SALESFORCE_ACCOUNT_ID, SALESFORCE_ACCOUNT_NAME, LEAD_SALES_ENGINEER_NAME,
       TYPE, IS_DCP_PARTNER, IS_DCS_PARTNER
FROM SALES.RAVEN.D_SALESFORCE_ACCOUNT_CUSTOMERS;

-- 11. SE manager
SELECT SALESFORCE_ACCOUNT_ID, SE_NAME, FIRST_LINE_MANAGER_NAME, IS_MANAGER
FROM SALES.RAVEN.RAVEN_SE_ACCOUNT_ASSIGNMENTS
WHERE FIRST_LINE_MANAGER_NAME IS NOT NULL
  AND SEGMENT = 'Commercial';

-- 12. Assigned ACE name/email
SELECT ACCOUNT_ID, ACE_NAME, ACE_EMAIL, USE_CASES, LAST_TOUCH
FROM ACCOUNT_ENGINEERING.WINGMAN.V_ACE_ACCOUNT_MAP;

-- 13. Topic hints per deal
SELECT OPPORTUNITY_ID, TOPIC_ID
FROM ACCOUNT_ENGINEERING.WINGMAN.ACE_TOPIC_HINTS;

-- 14. Logged-in user's name (greeting only)
SELECT NAME, DISPLAY_NAME
FROM SNOWFLAKE.ACCOUNT_USAGE.USERS
WHERE NAME = CURRENT_USER() AND DELETED_ON IS NULL;
